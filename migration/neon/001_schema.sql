begin;

create extension if not exists pgcrypto;

create table if not exists migrations (
  id bigint generated by default as identity primary key,
  migration varchar(255) not null,
  batch integer not null
);

create table if not exists users (
  id bigint generated by default as identity primary key,
  auth_user_id varchar(255) unique,
  name varchar(255) not null,
  email varchar(255) not null unique,
  phone varchar(32),
  email_verified_at timestamptz,
  password varchar(255) not null,
  remember_token varchar(100),
  created_at timestamptz,
  updated_at timestamptz
);

create table if not exists password_reset_tokens (
  email varchar(255) primary key,
  token varchar(255) not null,
  created_at timestamptz
);

create table if not exists sessions (
  id varchar(255) primary key,
  user_id bigint,
  ip_address varchar(45),
  user_agent text,
  payload text not null,
  last_activity integer not null
);
create index if not exists sessions_user_id_idx on sessions(user_id);
create index if not exists sessions_last_activity_idx on sessions(last_activity);

create table if not exists cache (
  key varchar(255) primary key,
  value text not null,
  expiration integer not null
);
create table if not exists cache_locks (
  key varchar(255) primary key,
  owner varchar(255) not null,
  expiration integer not null
);

-- Public endpoints use a salted, one-way bucket key rather than storing client
-- IP addresses.  The edge worker periodically removes expired buckets.
create table if not exists api_rate_limits (
  bucket_key varchar(128) primary key,
  window_started_at timestamptz not null,
  request_count integer not null default 0 check (request_count >= 0),
  expires_at timestamptz not null
);
create index if not exists api_rate_limits_expires_idx on api_rate_limits(expires_at);

create table if not exists jobs (
  id bigint generated by default as identity primary key,
  queue varchar(255) not null,
  payload text not null,
  attempts smallint not null check (attempts >= 0),
  reserved_at integer,
  available_at integer not null,
  created_at integer not null
);
create index if not exists jobs_queue_idx on jobs(queue);
create table if not exists failed_jobs (
  id bigint generated by default as identity primary key,
  uuid varchar(255) not null unique,
  connection text not null,
  queue text not null,
  payload text not null,
  exception text not null,
  failed_at timestamptz not null default now()
);
create table if not exists job_batches (
  id varchar(255) primary key,
  name varchar(255) not null,
  total_jobs integer not null,
  pending_jobs integer not null,
  failed_jobs integer not null,
  failed_job_ids text not null,
  options text,
  cancelled_at integer,
  created_at integer not null,
  finished_at integer
);
create table if not exists personal_access_tokens (
  id bigint generated by default as identity primary key,
  tokenable_type varchar(255) not null,
  tokenable_id bigint not null,
  name text not null,
  token varchar(64) not null unique,
  abilities text,
  last_used_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists personal_access_tokens_tokenable_idx on personal_access_tokens(tokenable_type, tokenable_id);
create index if not exists personal_access_tokens_expires_idx on personal_access_tokens(expires_at);

create table if not exists markets (
  id bigint generated by default as identity primary key,
  city varchar(255) not null,
  region char(2) not null,
  slug varchar(255) not null unique,
  time_zone varchar(255) not null,
  status varchar(255) not null default 'request_only',
  published boolean not null default false,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists markets_region_city_status_idx on markets(region, city, status);

create table if not exists service_types (
  id bigint generated by default as identity primary key,
  code varchar(255) not null unique,
  slug varchar(255) not null unique,
  name varchar(255) not null,
  category varchar(255) not null,
  description text,
  request_enabled boolean not null default true,
  instant_eligible boolean not null default false,
  published boolean not null default false,
  created_at timestamptz,
  updated_at timestamptz
);

create table if not exists addresses (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id) on delete set null,
  street varchar(255),
  unit varchar(255),
  city varchar(255),
  region char(2),
  postal_code varchar(12) not null,
  country char(2) not null default 'US',
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists addresses_region_city_postal_idx on addresses(region, city, postal_code);

create table if not exists leads (
  id bigint generated by default as identity primary key,
  public_id varchar(64) not null unique,
  customer_id bigint references users(id) on delete set null,
  name varchar(255) not null,
  email varchar(255),
  phone varchar(32),
  source varchar(255) not null default 'web',
  status varchar(255) not null default 'new',
  pipeline_stage varchar(32) not null default 'new_lead',
  lead_score smallint not null default 0 check (lead_score between 0 and 255),
  scored_at timestamptz,
  next_follow_up_at timestamptz,
  assigned_agent_id bigint references users(id) on delete set null,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists leads_status_follow_up_idx on leads(status, next_follow_up_at);
create index if not exists leads_email_idx on leads(email);
create index if not exists leads_phone_idx on leads(phone);
create index if not exists leads_pipeline_score_idx on leads(pipeline_stage, lead_score, id);
create index if not exists leads_agent_pipeline_idx on leads(assigned_agent_id, pipeline_stage, id);

create table if not exists consents (
  id bigint generated by default as identity primary key,
  lead_id bigint not null references leads(id) on delete cascade,
  channel varchar(255) not null,
  granted boolean not null,
  source varchar(255) not null,
  policy_version varchar(255) not null,
  recorded_at timestamptz not null,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists consents_lead_channel_recorded_idx on consents(lead_id, channel, recorded_at);

create table if not exists service_requests (
  id bigint generated by default as identity primary key,
  public_id varchar(64) not null unique,
  lead_id bigint not null references leads(id),
  address_id bigint not null references addresses(id),
  service_type_id bigint not null references service_types(id),
  market_id bigint references markets(id),
  status varchar(255) not null default 'received',
  property_type varchar(255) not null,
  frequency varchar(255),
  square_feet integer check (square_feet is null or square_feet >= 0),
  bedrooms smallint check (bedrooms is null or bedrooms >= 0),
  bathrooms smallint check (bathrooms is null or bathrooms >= 0),
  condition varchar(255),
  pets_on_site boolean,
  supplies_available varchar(255) not null default 'unsure',
  access_notes text,
  preferred_start_at timestamptz,
  time_zone varchar(255),
  scope_notes text,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists service_requests_status_created_idx on service_requests(status, created_at);
create index if not exists service_requests_market_start_idx on service_requests(market_id, preferred_start_at);

create table if not exists request_add_ons (
  service_request_id bigint not null references service_requests(id) on delete cascade,
  service_type_id bigint not null references service_types(id),
  primary key(service_request_id, service_type_id)
);

create table if not exists pricing_rules (
  id bigint generated by default as identity primary key,
  service_type_id bigint not null references service_types(id),
  market_id bigint not null references markets(id),
  version integer not null check (version >= 0),
  approved boolean not null default false,
  min_square_feet integer not null default 0 check (min_square_feet >= 0),
  max_square_feet integer check (max_square_feet is null or max_square_feet >= 0),
  base_cents integer not null check (base_cents >= 0),
  per_square_foot_cents integer not null default 0 check (per_square_foot_cents >= 0),
  per_bedroom_cents integer not null default 0 check (per_bedroom_cents >= 0),
  per_bathroom_cents integer not null default 0 check (per_bathroom_cents >= 0),
  deposit_percent smallint check (deposit_percent is null or deposit_percent between 0 and 100),
  effective_from timestamptz not null,
  effective_until timestamptz,
  created_at timestamptz,
  updated_at timestamptz,
  unique(service_type_id, market_id, version)
);
create index if not exists pricing_rules_market_approved_effective_idx on pricing_rules(market_id, approved, effective_from);

create table if not exists quotes (
  id bigint generated by default as identity primary key,
  public_id varchar(64) not null unique,
  service_request_id bigint not null references service_requests(id),
  approved_by bigint references users(id),
  pricing_rule_id bigint references pricing_rules(id),
  revision integer not null default 1 check (revision > 0),
  status varchar(255) not null default 'draft',
  currency char(3) not null default 'USD',
  subtotal_cents bigint not null check (subtotal_cents >= 0),
  tax_cents bigint not null default 0 check (tax_cents >= 0),
  total_cents bigint not null check (total_cents >= 0),
  deposit_cents bigint not null default 0 check (deposit_cents >= 0),
  expires_at timestamptz not null,
  accepted_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz,
  unique(service_request_id, revision)
);
create index if not exists quotes_status_expires_idx on quotes(status, expires_at);

create table if not exists quote_items (
  id bigint generated by default as identity primary key,
  quote_id bigint not null references quotes(id) on delete cascade,
  description varchar(255) not null,
  quantity integer not null default 1 check (quantity > 0),
  unit_cents bigint not null check (unit_cents >= 0),
  total_cents bigint not null check (total_cents >= 0)
);

create table if not exists bookings (
  id bigint generated by default as identity primary key,
  public_id varchar(64) not null unique,
  quote_id bigint not null unique references quotes(id),
  customer_id bigint references users(id),
  status varchar(255) not null default 'hold',
  start_at timestamptz not null,
  end_at timestamptz not null,
  time_zone varchar(255) not null,
  hold_expires_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists bookings_status_start_idx on bookings(status, start_at);

create table if not exists workers (
  id bigint generated by default as identity primary key,
  user_id bigint not null unique references users(id),
  approval_status varchar(255) not null default 'pending',
  approved_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz
);

create table if not exists booking_assignments (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references bookings(id),
  worker_id bigint not null references workers(id),
  status varchar(255) not null default 'offered',
  created_at timestamptz,
  updated_at timestamptz,
  unique(booking_id, worker_id)
);
create index if not exists booking_assignments_worker_status_idx on booking_assignments(worker_id, status);

create table if not exists payments (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references bookings(id),
  kind varchar(255) not null,
  status varchar(255) not null default 'created',
  currency char(3) not null default 'USD',
  amount_cents bigint not null check (amount_cents >= 0),
  refunded_cents bigint not null default 0 check (refunded_cents >= 0),
  stripe_intent_id varchar(255) unique,
  idempotency_key varchar(255) not null unique,
  environment varchar(8) not null default 'legacy',
  stripe_invoice_id varchar(255) unique,
  stripe_customer_id varchar(255),
  hosted_invoice_url text,
  invoice_pdf_url text,
  paid_at timestamptz,
  failed_at timestamptz,
  failure_code varchar(255),
  failure_message text,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists payments_booking_status_idx on payments(booking_id, status);
create index if not exists payments_booking_env_kind_status_idx on payments(booking_id, environment, kind, status);

create table if not exists calls (
  id bigint generated by default as identity primary key,
  lead_id bigint references leads(id),
  agent_id bigint references users(id),
  twilio_call_sid varchar(255) unique,
  direction varchar(255) not null,
  from_number varchar(32) not null,
  to_number varchar(32) not null,
  status varchar(255) not null default 'initiated',
  disposition varchar(255),
  notes text,
  started_at timestamptz,
  ended_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists calls_lead_created_idx on calls(lead_id, created_at);

create table if not exists campaigns (
  id bigint generated by default as identity primary key,
  name varchar(255) not null,
  channel varchar(255) not null,
  kind varchar(255) not null,
  status varchar(255) not null default 'draft',
  template_key varchar(255) not null,
  template_version integer not null,
  segment_filters jsonb not null,
  created_by bigint not null references users(id),
  scheduled_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists campaigns_status_scheduled_idx on campaigns(status, scheduled_at);

create table if not exists campaign_deliveries (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references campaigns(id),
  lead_id bigint not null references leads(id),
  status varchar(255) not null default 'queued',
  provider_message_id varchar(255),
  sent_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz,
  unique(campaign_id, lead_id)
);
create index if not exists campaign_deliveries_status_created_idx on campaign_deliveries(status, created_at);

create table if not exists provider_events (
  id bigint generated by default as identity primary key,
  provider varchar(255) not null,
  event_id varchar(255) not null,
  event_type varchar(255) not null,
  processed_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz,
  unique(provider, event_id)
);

create table if not exists audit_events (
  id bigint generated by default as identity primary key,
  actor_id bigint references users(id),
  entity_type varchar(255) not null,
  entity_id bigint not null,
  action varchar(255) not null,
  changes jsonb,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists audit_events_entity_idx on audit_events(entity_type, entity_id, created_at);

create table if not exists media (
  id bigint generated by default as identity primary key,
  service_request_id bigint references service_requests(id),
  booking_id bigint references bookings(id),
  uploaded_by bigint references users(id),
  private_path varchar(255) not null,
  mime_type varchar(255) not null,
  size_bytes bigint not null check (size_bytes >= 0),
  kind varchar(255) not null,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists media_booking_kind_idx on media(booking_id, kind);

create table if not exists permissions (
  id bigint generated by default as identity primary key,
  name varchar(255) not null,
  guard_name varchar(255) not null,
  created_at timestamptz,
  updated_at timestamptz,
  unique(name, guard_name)
);
create table if not exists roles (
  id bigint generated by default as identity primary key,
  name varchar(255) not null,
  guard_name varchar(255) not null,
  created_at timestamptz,
  updated_at timestamptz,
  unique(name, guard_name)
);
create table if not exists model_has_permissions (
  permission_id bigint not null references permissions(id) on delete cascade,
  model_type varchar(255) not null,
  model_id bigint not null,
  primary key(permission_id, model_id, model_type)
);
create index if not exists model_has_permissions_model_idx on model_has_permissions(model_id, model_type);
create table if not exists model_has_roles (
  role_id bigint not null references roles(id) on delete cascade,
  model_type varchar(255) not null,
  model_id bigint not null,
  primary key(role_id, model_id, model_type)
);
create index if not exists model_has_roles_model_idx on model_has_roles(model_id, model_type);
create table if not exists role_has_permissions (
  permission_id bigint not null references permissions(id) on delete cascade,
  role_id bigint not null references roles(id) on delete cascade,
  primary key(permission_id, role_id)
);

create table if not exists invoices (
  id bigint generated by default as identity primary key,
  public_id varchar(64) not null unique,
  number varchar(255) not null unique,
  booking_id bigint not null unique references bookings(id) on delete cascade,
  currency char(3) not null default 'USD',
  subtotal_cents bigint not null check (subtotal_cents >= 0),
  tax_cents bigint not null check (tax_cents >= 0),
  total_cents bigint not null check (total_cents >= 0),
  issued_at timestamptz not null,
  due_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz
);

create table if not exists service_plans (
  id bigint generated by default as identity primary key,
  public_id varchar(64) not null unique,
  customer_id bigint not null references users(id),
  originating_booking_id bigint not null unique references bookings(id),
  frequency varchar(255) not null,
  status varchar(255) not null default 'active',
  next_service_on date,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists service_plans_customer_status_idx on service_plans(customer_id, status);

create table if not exists plan_change_requests (
  id bigint generated by default as identity primary key,
  service_plan_id bigint not null references service_plans(id) on delete cascade,
  requested_by bigint not null references users(id),
  action varchar(255) not null,
  status varchar(255) not null default 'pending',
  reason text,
  resolved_at timestamptz,
  resolved_by bigint references users(id) on delete set null,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists plan_change_requests_plan_status_idx on plan_change_requests(service_plan_id, status);

create table if not exists agent_presence (
  agent_id bigint primary key references users(id) on delete cascade,
  available boolean not null default false,
  last_seen_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists agent_presence_available_seen_idx on agent_presence(available, last_seen_at);

create table if not exists review_requests (
  id bigint generated by default as identity primary key,
  booking_id bigint not null unique references bookings(id) on delete cascade,
  status varchar(255) not null default 'queued',
  attempts smallint not null default 0 check (attempts >= 0),
  attempt_token uuid,
  first_attempt_at timestamptz,
  last_attempt_at timestamptz,
  provider_message_id varchar(255),
  sent_at timestamptz,
  reason varchar(255),
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists review_requests_status_created_idx on review_requests(status, created_at);

create table if not exists staff_tasks (
  id bigint generated by default as identity primary key,
  public_id varchar(64) not null unique,
  service_request_id bigint not null references service_requests(id) on delete cascade,
  kind varchar(40) not null default 'quote_review',
  status varchar(24) not null default 'open',
  assigned_to bigint references users(id) on delete set null,
  due_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz,
  unique(service_request_id, kind)
);
create index if not exists staff_tasks_status_due_idx on staff_tasks(status, due_at);

create table if not exists quote_request_notifications (
  id bigint generated by default as identity primary key,
  service_request_id bigint not null unique references service_requests(id) on delete cascade,
  staff_task_id bigint not null unique references staff_tasks(id) on delete cascade,
  status varchar(32) not null default 'queued',
  payload jsonb not null,
  attempts smallint not null default 0 check (attempts >= 0),
  attempt_token uuid,
  first_attempt_at timestamptz,
  last_attempt_at timestamptz,
  provider_message_id varchar(255),
  sent_at timestamptz,
  failure_reason text,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists quote_request_notifications_status_created_idx on quote_request_notifications(status, created_at);

create table if not exists sales_prospects (
  id bigint generated by default as identity primary key,
  name varchar(255) not null,
  segment varchar(255) not null,
  email varchar(255) unique,
  phone varchar(32) unique,
  city varchar(255),
  region char(2),
  service_interest varchar(255) not null default 'Cleaning',
  source varchar(500) not null,
  status varchar(255) not null default 'new',
  notes text,
  next_follow_up_at timestamptz,
  assigned_agent_id bigint references users(id) on delete set null,
  lead_id bigint references leads(id) on delete set null,
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists sales_prospects_status_follow_up_idx on sales_prospects(status, next_follow_up_at);
create index if not exists sales_prospects_segment_idx on sales_prospects(segment, id);

create table if not exists prospect_reminders (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id),
  work_date date not null,
  status varchar(255) not null,
  provider_message_id varchar(255),
  created_at timestamptz,
  updated_at timestamptz,
  unique(user_id, work_date)
);

create table if not exists public_intakes (
  id bigint generated by default as identity primary key,
  public_id varchar(64) not null unique,
  kind varchar(24) not null,
  request_key varchar(120) not null unique,
  payload_hash varchar(64) not null,
  name varchar(255),
  email varchar(255) not null,
  status varchar(24) not null default 'open',
  details jsonb not null,
  marketing_email boolean not null default false,
  policy_version varchar(32) not null default '2026-10-16',
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists public_intakes_kind_idx on public_intakes(kind);
create index if not exists public_intakes_status_idx on public_intakes(status);

create table if not exists launch_mail_outbox (
  id bigint generated by default as identity primary key,
  message_key varchar(150) not null unique,
  recipient varchar(255) not null,
  subject varchar(255) not null,
  body text not null,
  status varchar(32) not null default 'queued',
  attempts smallint not null default 0 check (attempts >= 0),
  attempt_token uuid,
  first_attempt_at timestamptz,
  last_attempt_at timestamptz,
  sent_at timestamptz,
  provider_message_id varchar(255),
  failure_reason varchar(255),
  created_at timestamptz,
  updated_at timestamptz
);
create index if not exists launch_mail_outbox_status_idx on launch_mail_outbox(status);

commit;
